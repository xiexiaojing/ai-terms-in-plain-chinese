"""《强模型，救不了烂工程》第 1 章：把你自己的数字代进去，算一次调用到底付了几笔钱。

书里讲的是账单由四笔钱构成——输入、输出、缓存写、缓存读。这个脚本把那四笔钱算出来，
再往前推一步：算缓存几次才回本、一天一个月要花多少、换个模型差多少。

改下面 CONFIG 里的数字，然后：

    python3 第1章-算你自己的账单.py

不需要装任何东西，也不联网。
"""

import math

# ============================================================
# 改这里
# ============================================================

CONFIG = {
    # 一轮对话的形状。数字从你自己的日志里查，别拍脑袋。
    # 第 1 章讲了怎么查：响应体的 usage 字段里四个数都有。
    "系统提示词": 2000,      # token，每轮都要重发
    "历史与资料": 8000,      # token，每轮都要重发，而且越来越长
    "本轮提问": 200,         # token
    "思考": 1500,            # token，看不见但按输出价收费
    "回答": 800,             # token

    # 缓存。命中率从日志里的 cache_read_input_tokens 算，别用理论值。
    # 注：这里用命中率摊算缓存写，是个近似——真实情况下写入只发生在首次和失效之后。
    #     命中率取自真实日志时，这个近似跟实际账单的误差通常在几个百分点以内。
    "开缓存": True,
    "缓存的前缀": 10000,     # token，通常是系统提示词 + 稳定的那段资料
    "缓存命中率": 0.8,       # 0 到 1
    "缓存档位": "5分钟",     # "5分钟" 或 "1小时"

    # 规模
    "每天调用次数": 5000,

    # 价格：美元 / 百万 token。2026 年年中口径，过期了自己改。
    "模型": "opus",
}

价格表 = {
    #  名字      输入价   输出价     （美元 / 百万 token）
    "opus":    (5.00,   25.00),
    "sonnet":  (2.00,   10.00),
    "haiku":   (1.00,    5.00),
}

缓存档位倍率 = {"5分钟": 1.25, "1小时": 2.0}   # 写入按这个倍率加价
缓存读倍率 = 0.1                              # 读取按这个折扣

# ============================================================
# 下面不用改
# ============================================================


def 算一轮(c):
    输入价, 输出价 = 价格表[c["模型"]]
    百万 = 1_000_000

    请求体全长 = c["系统提示词"] + c["历史与资料"] + c["本轮提问"]
    响应体全长 = c["思考"] + c["回答"]

    if not c["开缓存"]:
        return {
            "普通输入": 请求体全长 * 输入价 / 百万,
            "缓存写": 0.0,
            "缓存读": 0.0,
            "输出": 响应体全长 * 输出价 / 百万,
        }

    前缀 = min(c["缓存的前缀"], 请求体全长)
    命中 = c["缓存命中率"]
    写倍率 = 缓存档位倍率[c["缓存档位"]]

    # 命中时前缀走缓存读价；没命中时前缀要重新写一遍缓存，按加价收
    return {
        "普通输入": (请求体全长 - 前缀) * 输入价 / 百万,
        "缓存写": 前缀 * (1 - 命中) * 输入价 * 写倍率 / 百万,
        "缓存读": 前缀 * 命中 * 输入价 * 缓存读倍率 / 百万,
        "输出": 响应体全长 * 输出价 / 百万,
    }


def 缓存回本线(c):
    """写一次缓存要多花钱，读几次才把这笔钱赚回来。

    书里说这个数是 2 次还是 3 次，取决于你在哪个档位。这里算给你看。
    """
    写倍率 = 缓存档位倍率[c["缓存档位"]]
    # 读 N 次的两种成本：不开缓存 = N；开缓存 = 写一次 + 读 N-1 次
    #   写倍率 + 缓存读倍率 × (N-1) < N   解出 N
    临界 = (写倍率 - 缓存读倍率) / (1 - 缓存读倍率)
    return 临界, math.ceil(临界)


def 报告():
    c = CONFIG
    四笔 = 算一轮(c)
    一轮 = sum(四笔.values())
    一天 = 一轮 * c["每天调用次数"]

    print(f"\n模型 {c['模型']}，一轮请求体 "
          f"{c['系统提示词'] + c['历史与资料'] + c['本轮提问']:,} token，"
          f"响应 {c['思考'] + c['回答']:,} token")
    print(f"缓存：{'开，' + c['缓存档位'] + '档，命中率 ' + str(int(c['缓存命中率']*100)) + '%' if c['开缓存'] else '关'}")
    print("\n一次调用，你付了这几笔：")
    for 名字, 钱 in 四笔.items():
        if 钱 > 0:
            print(f"  {名字:<8} ${钱:.6f}   {钱/一轮*100:5.1f}%")
    print(f"  {'合计':<8} ${一轮:.6f}")

    print(f"\n每天 {c['每天调用次数']:,} 次：${一天:,.2f}／天，${一天*30:,.2f}／月")

    if c["开缓存"]:
        临界, 第几次 = 缓存回本线(c)
        print(f"\n缓存回本线：同一段前缀读到第 {第几次} 次就回本"
              f"（精确临界 {临界:.2f} 次；{c['缓存档位']}档写入 {缓存档位倍率[c['缓存档位']]} 倍、"
              f"读取 {缓存读倍率} 倍）")
        关掉 = dict(c, 开缓存=False)
        省 = sum(算一轮(关掉).values()) - 一轮
        print(f"比不开缓存省：${省*c['每天调用次数']*30:,.2f}／月"
              if 省 > 0 else f"⚠️  比不开缓存还贵 ${-省*c['每天调用次数']*30:,.2f}／月，命中率太低了")

    print("\n换个模型：")
    for 名字 in 价格表:
        月 = sum(算一轮(dict(c, 模型=名字)).values()) * c["每天调用次数"] * 30
        标记 = "  ← 现在用的" if 名字 == c["模型"] else ""
        print(f"  {名字:<8} ${月:>10,.2f}／月{标记}")

    print("\n提醒：第 1 章和第 12 章都说过，跨厂商比单价不成立——两边一个 token 装的东西不一样多。")
    print("同一家内部换档位可以这么比，换厂商得拿同一批真实请求分别跑一遍数 token。\n")


if __name__ == "__main__":
    报告()
