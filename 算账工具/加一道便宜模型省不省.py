"""《强模型，救不了烂工程》第 7 章：先用便宜模型拦一道，到底省不省钱。

书里给的公式是：分级后单条成本 = 便宜价 + (1 - 拦截率) × 贵价
这个脚本把它反过来问一句更有用的：拦截率要做到多少，这道拦截才不白加。

    python3 第7章-加一道便宜模型省不省.py
"""

场景 = {
    "便宜模型单条成本": 0.002,   # 美元。跑一次分类/路由/预筛大概多少钱
    "贵模型单条成本":   0.075,   # 美元。真正干活那次多少钱
    "拦截率":          0.6,      # 便宜模型能独立处理掉的比例，从真实抽样里测
    "每天请求数":      5000,
}


def 报告():
    s = 场景
    便宜, 贵, r = s["便宜模型单条成本"], s["贵模型单条成本"], s["拦截率"]

    不分级 = 贵
    分级 = 便宜 + (1 - r) * 贵
    临界 = 便宜 / 贵

    print(f"\n便宜模型 ${便宜}／条，贵模型 ${贵}／条，拦截率 {r:.0%}")
    print(f"\n不分级：每条 ${不分级:.4f}")
    print(f"分级后：每条 ${分级:.4f}  = {便宜} + (1 - {r}) × {贵}")

    if 分级 < 不分级:
        省 = (不分级 - 分级) * s["每天请求数"] * 30
        print(f"\n省 {(不分级-分级)/不分级:.0%}，每月省 ${省:,.2f}")
    else:
        亏 = (分级 - 不分级) * s["每天请求数"] * 30
        print(f"\n⚠️  反而贵了 {(分级-不分级)/不分级:.0%}，每月多花 ${亏:,.2f}")

    print(f"\n临界拦截率：{临界:.1%}")
    print(f"  拦截率低于这个数，这道拦截就是白加的——便宜模型那笔钱花了，活还是贵模型干。")
    print(f"  它等于“便宜价 ÷ 贵价”，跟你的请求量、拦截率都没关系，只看两个模型的价差。")

    print("\n拦截率每变一档：")
    for x in [0.3, 0.4, 0.5, 0.6, 0.7, 0.8, 0.9]:
        单条 = 便宜 + (1 - x) * 贵
        差 = (不分级 - 单条) / 不分级
        标记 = "  ← 你现在的估计" if abs(x - r) < 0.01 else ""
        print(f"  {x:.0%}  每条 ${单条:.4f}  "
              f"{'省' if 差>0 else '亏'} {abs(差):.0%}{标记}")

    print(f"\n提醒：拦截率必须拿真实请求抽样测，不能拍。第 5 章说过，")
    print(f"分级最常见的失败方式是便宜模型拦下了它不该拦的，错误被带到下游才发现。\n")


if __name__ == "__main__":
    报告()
