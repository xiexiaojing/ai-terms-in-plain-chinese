"""《强模型，救不了烂工程》第 9 章：重试上限定几次。

书里给的公式：E(调用次数) = (1 - p^(n+1)) / (1 - p)，p 是单次失败率。
定重试上限时真正要看的是三件事一起看：最终成功率、成本放大多少、最坏要等多久。

    python3 第9章-重试几次才划算.py
"""

场景 = {
    "单次失败率": 0.1,      # 从你的日志里统计，别用理论值
    "单次成本":   0.075,    # 美元
    "单次耗时秒": 4.0,
    "退避基数秒": 1.0,      # sleep = random(0, min(cap, base × 2^n))
    "退避上限秒": 30.0,
}


def 期望次数(p, n):
    """调用次数的期望：1 + p + p² + ... + pⁿ"""
    return (1 - p ** (n + 1)) / (1 - p) if p < 1 else n + 1


def 报告():
    s = 场景
    p, 成本, 耗时 = s["单次失败率"], s["单次成本"], s["单次耗时秒"]

    print(f"\n单次失败率 {p:.0%}，单次 ${成本}／{耗时} 秒")
    print(f"\n{'重试上限':<8}{'最终成功率':<12}{'期望调用次数':<14}"
          f"{'期望成本':<12}{'最坏耗时':<10}")
    print("  " + "─" * 56)

    for n in range(0, 6):
        成功率 = 1 - p ** (n + 1)
        次数 = 期望次数(p, n)
        钱 = 次数 * 成本
        # 最坏情况：每次都失败，每次都等到退避上限
        退避 = sum(min(s["退避上限秒"], s["退避基数秒"] * 2 ** i) for i in range(n))
        最坏 = (n + 1) * 耗时 + 退避
        print(f"  {n:<8}{成功率:<12.4%}{次数:<14.3f}${钱:<11.4f}{最坏:.0f} 秒")

    print(f"\n怎么读这张表：")
    print(f"  成功率那一列很快就撞到天花板——失败率 {p:.0%} 时，重试 2 次已经到 "
          f"{1-p**3:.2%}，再加一次只多 {(1-p**4)-(1-p**3):.3%}。")
    print(f"  成本那一列却一直在涨，最坏耗时涨得更快。")
    print(f"  所以上限不是越大越好，是“成功率还在明显涨”和“最坏耗时还等得起”")
    print(f"  两条线的交点。多数线上服务落在 2 到 3。")

    print(f"\n注意：这套算法只对“重试有用”的失败成立——限流、超时、5xx。")
    print(f"参数错、内容被拒这类，重试一百次也是同一个结果，第 6 章讲了怎么分开。\n")


if __name__ == "__main__":
    报告()
