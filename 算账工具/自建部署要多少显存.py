"""《强模型，救不了烂工程》第 3 章：算 KV 缓存要占多少显存。

书里给了公式，但显存够不够是你自己那台机器的事，得代自己的数。
自建部署选卡、定并发数、定上下文上限的时候用这个。

    python3 第3章-自建部署要多少显存.py
"""

# ============================================================
# 改这里：模型结构参数，从模型的 config.json 里抄
# ============================================================

模型 = {
    "名字": "Qwen2.5-7B-Instruct",
    "层数": 28,              # num_hidden_layers
    "KV头数": 4,             # num_key_value_heads（不是 num_attention_heads）
    "每头维度": 128,          # hidden_size / num_attention_heads
    "每元素字节": 2,          # 半精度 2，八位量化 1
}

场景 = {
    "上下文长度": 32000,      # 每个请求平均占多长
    "并发请求数": 20,
    "显卡显存GB": 80,         # 单卡，比如 A100/H100 80G
    "权重占用GB": 15,         # 模型权重本身占的，7B 半精度约 15G
}

# ============================================================


def 每token字节(m):
    return 2 * m["层数"] * m["KV头数"] * m["每头维度"] * m["每元素字节"]


def 报告():
    b = 每token字节(模型)
    单请求 = b * 场景["上下文长度"] / 1024**3
    全部 = 单请求 * 场景["并发请求数"]
    可用 = 场景["显卡显存GB"] - 场景["权重占用GB"]

    print(f"\n{模型['名字']}：{模型['层数']} 层，{模型['KV头数']} 个 KV 头，"
          f"每头 {模型['每头维度']} 维，{模型['每元素字节']} 字节精度")
    print(f"\n每个 token 的 KV：{b:,} 字节 = {b/1024:.0f} KB")
    print(f"  算式  2 × {模型['层数']} × {模型['KV头数']} × "
          f"{模型['每头维度']} × {模型['每元素字节']} = {b:,}")

    print(f"\n一个 {场景['上下文长度']:,} token 的请求：{单请求:.2f} GB")
    print(f"{场景['并发请求数']} 个并发：{全部:.1f} GB")
    print(f"\n显卡 {场景['显卡显存GB']} GB － 权重 {场景['权重占用GB']} GB = "
          f"可用 {可用} GB")

    if 全部 <= 可用:
        还能加 = int((可用 - 全部) / 单请求)
        print(f"够用，还能再加 {还能加} 个并发（余 {可用-全部:.1f} GB）")
    else:
        最多 = int(可用 / 单请求)
        print(f"⚠️  不够，差 {全部-可用:.1f} GB。这张卡最多扛 {最多} 个并发，"
              f"或者把上下文压到 {int(可用/场景['并发请求数']/(b/1024**3)):,} token")

    print(f"\n把上下文砍一半到 {场景['上下文长度']//2:,}："
          f"{全部/2:.1f} GB，能上 {int(可用/(单请求/2))} 个并发")
    print("这就是第 3 章说的：上下文长度不只是钱的事，是你那张卡能同时接几个人的事。\n")


if __name__ == "__main__":
    报告()
